    internal static (int Npc, int Map, int Element)[] ForLevel(int level) => Targets[Math.Clamp(level, 1, 99) - 1];
    internal static long TaskId(int level, int slot) => FirstTask + (Math.Clamp(level, 1, 99) - 1) * Slots + slot;
    internal static bool IsOption(long id) => id >= FirstTask && id < FirstTask + 99 * Slots;

    internal static int[] Choose(int level, long cycle, int previousNpc)
    {
        var targets = ForLevel(level);
        var eligible = new List<int>();
        for (int i = 0; i < targets.Length; i++)
        {
            int index = (int)((Math.Max(0, cycle) + i) % targets.Length);
            if (targets[index].Npc != previousNpc && targets[index].Npc != ScarceNineTail) eligible.Add(index);
        }
        if (eligible.Count == 0)
            for (int i = 0; i < targets.Length; i++)
                if (targets[i].Npc != ScarceNineTail) { eligible.Add(i); break; }
        foreach (int first in eligible)
            foreach (int second in eligible)
                if (first != second && targets[first].Map != targets[second].Map && targets[first].Element != targets[second].Element)
                    return [first, second];
        return eligible.Count == 0 ? [] : [eligible[0]];
    }
